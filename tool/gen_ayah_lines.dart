// Writes lib/data/ayah_lines.dart: each ayah's estimated length in lines of
// the 15-line Madani mushaf, in tenths, from its letter count.
//
//   dart run tool/gen_ayah_lines.dart
import 'dart:convert';
import 'dart:io';
import 'dart:math';

/// Letters in an average mushaf line (diacritics and spaces don't count).
const lettersPerLine = 37.18;

void main() {
  final surahs = jsonDecode(File('assets/quran/quran.json').readAsStringSync()) as List;
  final letter = RegExp(r'\p{L}', unicode: true);
  var total = 0, amma = 0;
  final out = StringBuffer()
    ..writeln('// Generated by tool/gen_ayah_lines.dart. Estimated mushaf lines per ayah, in tenths.')
    ..writeln()
    ..writeln('const ayahLineTenths = <List<int>>[');
  for (final (i, surah) in (surahs).indexed) {
    final row = [
      for (final ayah in surah as List)
        max(1, (letter.allMatches((ayah as List)[0] as String).length / lettersPerLine * 10).round()),
    ];
    final sum = row.fold(0, (a, b) => a + b);
    total += sum;
    if (i + 1 >= 78) amma += sum;
    out.writeln('  [${_wrap(row)}],');
  }
  out.writeln('];');
  File('lib/data/ayah_lines.dart').writeAsStringSync(out.toString());
  stdout.writeln('Total ${total / 10} lines; Juz Amma (78–114) ${amma / 10} lines.');
}

/// The numbers, wrapped so no line passes 120 characters (`dart format` would put one per line).
String _wrap(List<int> row) {
  final lines = <String>[];
  var line = '';
  for (final n in row) {
    final next = line.isEmpty ? '$n' : '$line, $n';
    if (next.length > 110) {
      lines.add('$line,');
      line = '$n';
    } else {
      line = next;
    }
  }
  lines.add(line);
  return lines.join('\n    ');
}
